"""Download optional real-page inputs and record their SHA-256 identities.

The synthetic fixtures are generated by content_benchmark and need no network.
Live documentation may change; each new snapshot is a new workload. Use the
saved sources JSON to compare identities with the published measurement.
"""

import argparse
import hashlib
import json
import pathlib
import subprocess


SOURCES = {
    "rust-ownership.html": "https://doc.rust-lang.org/book/ch04-01-what-is-ownership.html",
    "python-asyncio.html": "https://docs.python.org/3/library/asyncio-eventloop.html",
    "sqlite-select.html": "https://www.sqlite.org/lang_select.html",
}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("directory", type=pathlib.Path)
    args = parser.parse_args()
    args.directory.mkdir(parents=True, exist_ok=True)
    results = []
    for name, url in SOURCES.items():
        destination = args.directory / name
        subprocess.run([
            "curl", "--fail", "--silent", "--show-error", "--location",
            "--max-time", "60", url, "--output", str(destination),
        ], check=True)
        data = destination.read_bytes()
        results.append({
            "filename": name, "url": url, "bytes": len(data),
            "sha256": hashlib.sha256(data).hexdigest(),
        })
    (args.directory / "sources.json").write_text(json.dumps(results, indent=2) + "\n")
    print(json.dumps(results, indent=2))


if __name__ == "__main__":
    main()
